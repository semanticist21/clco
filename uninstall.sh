#!/usr/bin/env bash
# clco uninstaller.
#   curl -fsSL https://raw.githubusercontent.com/semanticist21/clco/main/uninstall.sh | bash
#   ... --full   : also remove config and the GitHub token (~/.config/clco)
set -euo pipefail

CLCO_DIR="${CLCO_DIR:-$HOME/.local/share/clco}"
BIN_DIR="${BIN_DIR:-$HOME/.local/bin}"

log() { printf '\033[1;36m==>\033[0m %s\n' "$*"; }
fail() { printf '\033[1;31mError:\033[0m %s\n' "$*" >&2; exit 1; }

verify_install() {
  local target="$1"
  [ -d "$target/.git" ] \
    || fail "$target is not a clco install (git repo) - refusing to delete it"
  grep -Eq '^[[:space:]]*"name"[[:space:]]*:[[:space:]]*"(@semanticist14/)?clco"[[:space:]]*,?[[:space:]]*$' \
    "$target/package.json" \
    || fail "$target is not a clco install (package name) - refusing to delete it"
  local origin
  origin="$(git -C "$target" remote get-url origin 2>/dev/null || true)"
  case "$origin" in
    https://github.com/semanticist21/clco.git|git@github.com:semanticist21/clco.git) ;;
    *) fail "$target does not point to the canonical clco repository - refusing to delete it" ;;
  esac
}

# Validate every target before removing even the launcher.
for target in "$CLCO_DIR" "$CLCO_DIR.previous"; do
  if [ -e "$target" ]; then verify_install "$target"; fi
done

if [ -f "$BIN_DIR/clco" ]; then
  expected="$(printf 'CLCO_APP_DIR=%q' "$CLCO_DIR")"
  legacy="$(printf 'CLCO_APP_DIR="%s"' "$CLCO_DIR")"
  grep -Eq '^# clco launcher( v[0-9]+ \(generated by scripts/write-launcher\.sh\)| \(installed by install\.sh\))$' "$BIN_DIR/clco" \
    || fail "$BIN_DIR/clco is not a generated clco launcher - refusing to delete it"
  if ! grep -Fxq "$expected" "$BIN_DIR/clco" && ! grep -Fxq "$legacy" "$BIN_DIR/clco"; then
    fail "$BIN_DIR/clco points to another installation - refusing to delete it"
  fi
fi

removed=0
if [ -f "$BIN_DIR/clco" ]; then rm -f "$BIN_DIR/clco"; log "Removed: $BIN_DIR/clco"; removed=1; fi
if [ -d "$CLCO_DIR" ]; then
  rm -rf "$CLCO_DIR"; log "Removed: $CLCO_DIR"; removed=1
fi
if [ -d "$CLCO_DIR.previous" ]; then
  rm -rf "$CLCO_DIR.previous"; log "Removed: $CLCO_DIR.previous"; removed=1
fi
if [ -d "$CLCO_DIR.update.lock" ]; then
  rmdir "$CLCO_DIR.update.lock" \
    || fail "$CLCO_DIR.update.lock is not empty - verify no update is running before removing it"
  log "Removed stale update lock: $CLCO_DIR.update.lock"; removed=1
fi

if [ "${1:-}" = "--full" ]; then
  if [ -d "$HOME/.config/clco" ]; then
    rm -rf "$HOME/.config/clco"
    log "Removed: ~/.config/clco (including the GitHub token)"
  fi
else
  [ -d "$HOME/.config/clco" ] && log "Kept config: ~/.config/clco (including the GitHub token) - remove it with: $0 --full"
fi

[ "$removed" = "1" ] || [ "${1:-}" = "--full" ] || log "Nothing to remove"
log "Done"
